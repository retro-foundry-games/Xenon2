"""Generate the game's state declarations from native/src/game.symbols.

  uv run tools/gen_symbols.py [--ram RAM.bin]       (from the project root)

native/src/game.symbols and native/src/symbols/*.symbols (one file for each module, so that several people can add lines), one line each (`;` starts a comment):
  type NAME SIZE                          a record type (fields in native/src/types.h), SIZE bytes
  var  NAME 0xADDR TYPE ; comment         a variable (scalar, pointer-sized 4, or `struct NAME` / a `type` above)
  arr  NAME 0xADDR TYPE COUNT ; comment   an array of them (a plain buffer: TYPE uint8_t)
  tab  NAME 0xADDR TYPE COUNT ; comment   constant data: the C holds the values in data.c (copied from --ram, big endian)
TYPE: uint8_t int8_t uint16_t int16_t uint32_t int32_t, a pointer `T *` (4 bytes), or a record type name; `volatile` in front for what an interrupt changes.

Writes (generated files are checked in; do not edit them):
  native/src/game.h           struct Xenon, the game's whole memory: every other struct is a member or an element of a member (members at the offsets of the original's addresses, gaps PAD(n)), LAYOUT_ASSERTs,
                              and, for the Amiga build, extern declarations (the variable is at its address: game.ld)
  native/src/game.ld          NAME = 0xADDR;
  native/src/guest_members.h  the SDL port's table: original address, size, where it is in struct Xenon
  native/src/data.c           the constant tables
"""
import re, sys, os, struct, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'native', 'src')
SIZES = {'uint8_t': 1, 'int8_t': 1, 'uint16_t': 2, 'int16_t': 2, 'uint32_t': 4, 'int32_t': 4, 'irq_fn': 4}   # irq_fn: void (*)(void), types.h

def parse():
    types, syms = {}, []
    files = [os.path.join(SRC, 'game.symbols')] + sorted(glob.glob(os.path.join(SRC, 'symbols', '*.symbols')))
    lines = [(os.path.basename(f), n, line) for f in files if os.path.exists(f) for n, line in enumerate(open(f), 1)]
    for fname, n, line in lines:
        line = line.split(';')[0].strip()
        if not line: continue
        t = line.split()
        if t[0] == 'type':
            types[t[1]] = int(t[2], 0)
        elif t[0] in ('var', 'arr', 'tab'):
            kind, name, addr = t[0], t[1], int(t[2], 0)
            ctype = ' '.join(t[3:-1]) if kind != 'var' else ' '.join(t[3:])
            count = int(t[-1], 0) if kind != 'var' else None
            if kind != 'var' and not re.fullmatch(r'(0x[0-9a-fA-F]+|\d+)', t[-1]): raise SystemExit('%s:%d: count missing' % (fname, n))
            syms.append(dict(kind=kind, name=name, addr=addr, ctype=ctype, count=count, line=n, file=fname))
        else:
            raise SystemExit('%s:%d: unknown line %r' % (fname, n, line))
    for s in syms:
        base = s['ctype'].replace('volatile ', '', 1).strip()
        if base.endswith('*'): size = 4
        elif base in SIZES: size = SIZES[base]
        elif base in types: size = types[base]
        else: raise SystemExit('%s:%d: unknown type %r' % (s['file'], s['line'], base))
        s['elem'] = size
        s['size'] = size * (s['count'] or 1)
    syms.sort(key=lambda s: s['addr'])
    for a, b in zip(syms, syms[1:]):
        if a['addr'] + a['size'] > b['addr']:
            raise SystemExit('overlap: %s (%s, 0x%x..0x%x) and %s (%s, 0x%x): one address, one name: reuse the existing symbol' % (a['name'], a['file'], a['addr'], a['addr'] + a['size'], b['name'], b['file'], b['addr']))
    names = {}
    for s in syms:
        if s['name'] in names: raise SystemExit('the name %s is in %s and %s' % (s['name'], names[s['name']], s['file']))
        names[s['name']] = s['file']
    return types, syms

def decl(s, name=None):
    name = name or s['name']
    ct = s['ctype']
    plain = ct.replace('volatile ', '', 1).strip()
    if plain not in SIZES and not plain.endswith('*'): ct = ct.replace(plain, 'struct %s' % plain)
    const = 'const ' if s['kind'] == 'tab' else ''
    if ct.endswith('*'): head = '%s%s' % (const, ct)
    else: head = '%s%s' % (const, ct)
    suffix = '[%d]' % s['count'] if s['count'] else ''
    return '%s %s%s' % (head, name, suffix)

def write_state(types, syms):
    out = ['/* Generated by tools/gen_symbols.py from game.symbols: do not edit.  struct Xenon is the whole memory of the game. */', '#ifndef GAME_H', '#define GAME_H', '#include <stdint.h>', '#include <stddef.h>', '#include "types.h"', '']
    heads = sorted(glob.glob(os.path.join(SRC, 'types_*.h')))
    out += ['#include "%s"' % os.path.basename(h) for h in heads]
    out += ['_Static_assert(sizeof(struct %s) == %d, "struct %s has not the size game.symbols gives");' % (n, sz, n) for n, sz in sorted(types.items())]
    out.append('')
    out += ['#define LAYOUT_ASSERT(member, address) _Static_assert(offsetof(struct Xenon2, member) == (address), #member " is not at its address")',
            '/* The game\'s memory, byte for byte: the members are at the offsets of the original\'s addresses, the gaps are padding.  The SDL port defines it (guest.c);',
            ' * the Amiga build links it at address 0 (game.ld). */',
            'struct Xenon2 {']
    pos, padn = 0, 0
    for s in syms:
        if s['addr'] > pos:
            out.append('    uint8_t pad_0x%x[%d];' % (s['addr'], s['addr'] - pos)); padn += 1
        out.append('    %s;  /* $%06X %s */' % (decl(s), s['addr'], s['kind']))
        pos = s['addr'] + s['size']
    out += ['};', 'extern struct Xenon2 xenon2;']
    out += ['LAYOUT_ASSERT(%s, 0x%x);' % (s['name'], s['addr']) for s in syms]
    out.append('#ifndef GAME_NO_MEMBER_MACROS   /* (the host files that name the members themselves define it) */')
    for s in syms:
        out.append('#define %s (xenon2.%s)' % (s['name'], s['name']))
    out.append('#endif')
    out += ['', '#include "amiga/hw.h"', '', '#endif']
    text = '\n'.join(out) + '\n'
    open(os.path.join(SRC, 'game.h'), 'w').write(text)

def unresolved_placeholders():
    """fn_ADDR names the C uses for code that has no C (it never ran in the recorded run): ADDR -> True."""
    used, defined = set(), set()
    for f in glob.glob(os.path.join(SRC, '*.c')) + glob.glob(os.path.join(SRC, '*.h')):
        text = open(f).read()
        used |= {int(m.group(1), 16) for m in re.finditer(r'\bfn_([0-9a-f]{6})\b', text)}
        defined |= {int(m.group(1), 16) for m in re.finditer(r'\bfn_([0-9a-f]{6})\s*\([^;{]*\)\s*\{', text)}
    return sorted(used - defined)

def write_ld(syms):
    head = ('/* Generated by tools/gen_symbols.py: do not edit.  The code is one hunk linked at the address it will run at (BASE, above the\n'
            ' * original\'s memory), so it needs no relocation; the variables and tables are absolute: they are where the original keeps them. */\n'
            'SECTIONS {\n    .text 0xc0000 : { *(.text .text.*) *(.rodata .rodata.*) *(.data .data.*) }\n'
            '    /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) }\n}\n')
    placeholders = ''.join('_fn_%06x = 0x%x;   /* code that never ran: the original\'s, at its address */\n' % (a, a) for a in unresolved_placeholders())
    open(os.path.join(SRC, 'game.ld'), 'w').write(head + '_xenon2 = 0x0;   /* the game\'s memory: struct Xenon2 (game.h) */\n' + placeholders)
    stubs = ['/* Generated by tools/gen_symbols.py: do not edit.  Code of the original that never ran in the recorded run and has no C: the port logs a call. */',
             '#include "host.h"', '']
    for a in unresolved_placeholders():
        stubs.append('void fn_%06x(void) { host_unimplemented(0x%x); }' % (a, a))
    os.makedirs(os.path.join(SRC, 'sdl'), exist_ok=True)
    open(os.path.join(SRC, 'sdl', 'unimplemented.c'), 'w').write('\n'.join(stubs) + '\n')

def write_members(syms):
    """ptr: 1 = the members (or the elements) are addresses of the original's data (the loader makes them pointers), 2 = of its code (the C function);
    rec: the record type of the elements (their fields are byte-swapped by swap_record_NAME, tools/gen_records.py), else 0."""
    out = ['/* Generated by tools/gen_symbols.py: do not edit.  The members sorted by the original\'s address. */',
           'static const struct { uint32_t address, size, elem; int ptr; const char *rec; void *dst; const char *name; } guest_members[] = {']
    for s in syms:
        plain = s['ctype'].replace('volatile ', '', 1).strip()
        isptr = 2 if plain == 'irq_fn' else (1 if plain.endswith('*') else 0)   # 1: address of data, 2: address of code
        rec = '"%s"' % plain if plain not in SIZES and not plain.endswith('*') else '0'
        out.append('    { 0x%x, %d, %d, %d, %s, (void *)&xenon2.%s, "%s" },' % (s['addr'], s['size'], s['elem'], isptr, rec, s['name'], s['name']))
    out.append('};')
    open(os.path.join(SRC, 'guest_members.h'), 'w').write('\n'.join(out) + '\n')

def write_members_lua(syms):
    """dev/members.lua: the named members (address, size, name, element size, kind) for the lockstep comparison (generated, not checked in)."""
    out = ['-- Generated by tools/gen_symbols.py: do not edit.  The named members of the game\'s memory.', 'return {']
    for s in syms:
        out.append('  { 0x%x, %d, "%s", %d, "%s" },' % (s['addr'], s['size'], s['name'], s['elem'], s['kind']))
    out.append('}')
    d = os.path.join(ROOT, 'dev')
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'members.lua'), 'w').write('\n'.join(out) + '\n')

def record_table(s, ram):
    """a constant table of a record type: one initializer per element, the fields in the order of the struct (big endian in the image);
    an address field is an address of the original's (data or code) as a constant: the Amiga build is linked at the original's addresses."""
    sys.path.insert(0, os.path.join(ROOT, 'tools'))
    import gen_records
    gen_records.TYPEDEFS.update(gen_records.typedef_kinds())
    structs = gen_records.parse_structs()
    size, _, items = gen_records.layout(s['ctype'], structs, {})
    rows = []
    for i in range(s['count']):
        base = s['addr'] + i * size
        vals = []
        for off, kind, count, sz in items:
            if kind.startswith('rec:') or count != 1: raise SystemExit('tab %s: a field of %s is not a scalar or an address' % (s['name'], s['ctype']))
            v = int.from_bytes(ram[base + off: base + off + sz], 'big', signed=False)
            vals.append(str(v) if kind in ('8', '16', '32') else ('0' if v == 0 else '(void *)0x%x' % v))
        rows.append('{ %s }' % ', '.join(vals))
    return 'const struct %s %s[%d] = { %s };' % (s['ctype'], s['name'], s['count'], ', '.join(rows))

def write_data(syms, ram, types):
    out = ['/* Generated by tools/gen_symbols.py from the original\'s memory: do not edit. */', '#define GAME_NO_MEMBER_MACROS   /* the tables are objects of their own here, not members of struct Xenon2 */', '#include "game.h"', '']
    for s in syms:
        if s['kind'] != 'tab': continue
        if ram is None: continue
        if s['elem'] in (1, 2, 4) and s['ctype'] in SIZES:
            fmt = {1: '>B', 2: '>H', 4: '>I'}[s['elem']]
            if s['ctype'].startswith('int'): fmt = fmt.lower()
            vals = [struct.unpack(fmt, ram[s['addr'] + i * s['elem']: s['addr'] + (i + 1) * s['elem']])[0] for i in range(s['count'])]
            body = ', '.join(str(v) for v in vals)
            out.append('const %s %s[%d] = { %s };' % (s['ctype'], s['name'], s['count'], body))
        elif s['ctype'] in types:
            out.append(record_table(s, ram))
        else:
            raise SystemExit('tab %s: only tables of uint8/16/32 or of a record type are supported' % s['name'])
    open(os.path.join(SRC, 'data.c'), 'w').write('\n'.join(out) + '\n')

def main():
    ram = None
    if '--ram' in sys.argv: ram = open(sys.argv[sys.argv.index('--ram') + 1], 'rb').read()
    types, syms = parse()
    write_state(types, syms); write_ld(syms); write_members(syms); write_members_lua(syms); write_data(syms, ram, types)
    print(len(syms), 'symbols')
    import subprocess
    subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'gen_records.py')], check=True)
main()
