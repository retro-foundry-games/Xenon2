"""Generate the game's state declarations from native/src/game.symbols.

  uv run tools/gen_symbols.py [--ram RAM.bin]       (from the project root)

game.symbols, one line each (`;` starts a comment):
  type NAME SIZE                          a record type (fields in native/src/types.h), SIZE bytes
  var  NAME 0xADDR TYPE ; comment         a variable (scalar, pointer-sized 4, or `struct NAME` / a `type` above)
  arr  NAME 0xADDR TYPE COUNT ; comment   an array of them (a plain buffer: TYPE uint8_t)
  tab  NAME 0xADDR TYPE COUNT ; comment   constant data: the C holds the values in data.c (copied from --ram, big endian)
TYPE: uint8_t int8_t uint16_t int16_t uint32_t int32_t, a pointer `T *` (4 bytes), or a record type name.

Writes (generated files are checked in; do not edit them):
  native/src/game_state.h     struct Xenon (members at the offsets of the original's addresses, gaps PAD(n)), LAYOUT_ASSERTs,
                              and, for the Amiga build, extern declarations (the variable is at its address: game.ld)
  native/src/game.ld          NAME = 0xADDR;
  native/src/guest_members.h  the SDL port's table: original address, size, where it is in struct Xenon
  native/src/data.c           the constant tables
"""
import re, sys, os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'native', 'src')
SIZES = {'uint8_t': 1, 'int8_t': 1, 'uint16_t': 2, 'int16_t': 2, 'uint32_t': 4, 'int32_t': 4}

def parse():
    types, syms = {}, []
    for n, line in enumerate(open(os.path.join(SRC, 'game.symbols')), 1):
        line = line.split(';')[0].strip()
        if not line: continue
        t = line.split()
        if t[0] == 'type':
            types[t[1]] = int(t[2], 0)
        elif t[0] in ('var', 'arr', 'tab'):
            kind, name, addr = t[0], t[1], int(t[2], 0)
            ctype = ' '.join(t[3:-1]) if kind != 'var' else ' '.join(t[3:])
            count = int(t[-1], 0) if kind != 'var' else None
            if kind != 'var' and not re.fullmatch(r'(0x[0-9a-fA-F]+|\d+)', t[-1]): raise SystemExit('%s:%d: count missing' % ('game.symbols', n))
            syms.append(dict(kind=kind, name=name, addr=addr, ctype=ctype, count=count, line=n))
        else:
            raise SystemExit('game.symbols:%d: unknown line %r' % (n, line))
    for s in syms:
        base = s['ctype']
        if base.endswith('*'): size = 4
        elif base in SIZES: size = SIZES[base]
        elif base in types: size = types[base]
        else: raise SystemExit('game.symbols:%d: unknown type %r' % (s['line'], base))
        s['elem'] = size
        s['size'] = size * (s['count'] or 1)
    syms.sort(key=lambda s: s['addr'])
    for a, b in zip(syms, syms[1:]):
        if a['addr'] + a['size'] > b['addr']:
            raise SystemExit('overlap: %s (0x%x..0x%x) and %s (0x%x)' % (a['name'], a['addr'], a['addr'] + a['size'], b['name'], b['addr']))
    return types, syms

def decl(s, name=None):
    name = name or s['name']
    ct = s['ctype']
    ct = ('struct %s' % ct if ct not in SIZES and not ct.endswith('*') else ct)
    const = 'const ' if s['kind'] == 'tab' else ''
    if ct.endswith('*'): head = '%s%s' % (const, ct)
    else: head = '%s%s' % (const, ct)
    suffix = '[%d]' % s['count'] if s['count'] else ''
    return '%s %s%s' % (head, name, suffix)

def write_state(types, syms):
    out = ['/* Generated by tools/gen_symbols.py from game.symbols: do not edit. */', '#ifndef GAME_STATE_H', '#define GAME_STATE_H', '#include <stdint.h>', '#include <stddef.h>', '#include "types.h"', '']
    out += ['#ifdef GAME_SDL', '/* The SDL port: the game\'s memory is one struct; with MATCH_MEMORY_LAYOUT its members are at the offsets of the original\'s addresses. */',
            '#ifdef MATCH_MEMORY_LAYOUT', '#define PAD(n, id) uint8_t pad_##id[n];', '#else', '#define PAD(n, id)', '#endif',
            '#define LAYOUT_ASSERT(member, address) _Static_assert(offsetof(struct Xenon, member) == (address), #member " is not at its address")',
            'struct Xenon {']
    pos, padn = 0, 0
    for s in syms:
        if s['addr'] > pos:
            out.append('    PAD_N(%d, 0x%x)' % (s['addr'] - pos, padn)); padn += 1
        out.append('    %s;  /* $%06X %s */' % (decl(s), s['addr'], s['kind']))
        pos = s['addr'] + s['size']
    out += ['};', 'extern struct Xenon xenon;']
    out += ['#ifdef MATCH_MEMORY_LAYOUT'] + ['LAYOUT_ASSERT(%s, 0x%x);' % (s['name'], s['addr']) for s in syms] + ['#endif']
    for s in syms:
        out.append('#define %s (xenon.%s)' % (s['name'], s['name']))
    out += ['#else', '/* The Amiga build: each variable is at its address (game.ld). */']
    out += ['extern %s;' % decl(s) for s in syms]
    out += ['#endif', '', '#endif']
    text = '\n'.join(out) + '\n'
    # PAD_N(n, id): a unique member name per gap
    text = re.sub(r'PAD_N\((\d+), (0x[0-9a-f]+)\)', lambda m: 'PAD(%s, %s)' % (m.group(1), m.group(2)), text)
    open(os.path.join(SRC, 'game_state.h'), 'w').write(text)

def write_ld(syms):
    head = ('/* Generated by tools/gen_symbols.py: do not edit.  The code is one hunk linked at the address it will run at (BASE, above the\n'
            ' * original\'s memory), so it needs no relocation; the variables and tables are absolute: they are where the original keeps them. */\n'
            'SECTIONS {\n    .text 0xc0000 : { *(.text .text.*) *(.rodata .rodata.*) *(.data .data.*) }\n'
            '    /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) }\n}\n')
    open(os.path.join(SRC, 'game.ld'), 'w').write(head + ''.join('_%s = 0x%x;\n' % (s['name'], s['addr']) for s in syms))

def write_members(syms):
    out = ['/* Generated by tools/gen_symbols.py: do not edit.  The members sorted by the original\'s address. */',
           'static const struct { uint32_t address, size, elem; void *dst; const char *name; } guest_members[] = {']
    for s in syms:
        out.append('    { 0x%x, %d, %d, &xenon.%s, "%s" },' % (s['addr'], s['size'], s['elem'], s['name'], s['name']))
    out.append('};')
    open(os.path.join(SRC, 'guest_members.h'), 'w').write('\n'.join(out) + '\n')

def write_data(syms, ram):
    out = ['/* Generated by tools/gen_symbols.py from the original\'s memory: do not edit. */', '#include "game.h"', '']
    for s in syms:
        if s['kind'] != 'tab': continue
        if ram is None: continue
        if s['elem'] in (1, 2, 4) and s['ctype'] in SIZES:
            fmt = {1: '>B', 2: '>H', 4: '>I'}[s['elem']]
            if s['ctype'].startswith('int'): fmt = fmt.lower()
            vals = [struct.unpack(fmt, ram[s['addr'] + i * s['elem']: s['addr'] + (i + 1) * s['elem']])[0] for i in range(s['count'])]
            body = ', '.join(str(v) for v in vals)
            out.append('const %s %s[%d] = { %s };' % (s['ctype'], s['name'], s['count'], body))
        else:
            raise SystemExit('tab %s: only scalar tables of uint8/16/32 are supported' % s['name'])
    open(os.path.join(SRC, 'data.c'), 'w').write('\n'.join(out) + '\n')

def main():
    ram = None
    if '--ram' in sys.argv: ram = open(sys.argv[sys.argv.index('--ram') + 1], 'rb').read()
    types, syms = parse()
    write_state(types, syms); write_ld(syms); write_members(syms); write_data(syms, ram)
    print(len(syms), 'symbols')
main()
