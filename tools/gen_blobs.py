#!/usr/bin/env python3
"""native/src/blobs/levelN.blob -> native/src/blobs.h and native/src/guest_blob.h.
blobs.h: struct LevelNBlob, the layout of the code blob of level N at $54E00, and `levelN_blob`, the blob as that struct.
guest_blob.h: the members the host build converts (big endian -> its byte order, addresses -> pointers) when the blob is loaded.

A line is `ADDR name TYPE [COUNT]` (hex address): u8 u16 s16 u32 (integers), ptr (a pointer to the blob, const uint8_t *), code (a pointer to
a function of the original's code: the C function), or the name of a record.  `record NAME SIZE` starts a record: lines `OFFSET name TYPE [COUNT]`
(decimal offset), `end` closes it.  u16 u32 and ptr members are native
(converted on load: read and write them directly); u8 members are bytes, also the data the C reads with rd16/rd32 (big endian records, pictures, cells).
COUNT defaults to 1; a u8 member without it runs to the next one.  What no member covers is padding (the level's code)."""
import re, sys, pathlib

BASE = 0x54E00
SIZE = {'u8': 1, 'u16': 2, 's16': 2, 'u32': 4, 'ptr': 4, 'code': 4}
KIND = {'u8': 0, 'u16': 0, 's16': 0, 'u32': 0, 'ptr': 1, 'code': 2}
CT = {'u8': 'uint8_t', 'u16': 'uint16_t', 's16': 'int16_t', 'u32': 'uint32_t', 'ptr': 'const uint8_t *', 'code': 'void (*'}
root = pathlib.Path(__file__).resolve().parent.parent / 'native' / 'src'
out = ['/* Generated by tools/gen_blobs.py from the blob files in blobs/: do not edit.  The code blob of each level at $54E00. */',
       '#ifndef BLOBS_H', '#define BLOBS_H', '#include <stdint.h>', '#include <stddef.h>', '#include "draw.h"', '',
       '#define BLOB_BASE 0x54E00', '#define BLOB_ADDR(S, f) (BLOB_BASE + offsetof(struct S, f))', '',
       '#define BLOB_PAD_CAT2(a, b) a##b', '#define BLOB_PAD_CAT(a, b) BLOB_PAD_CAT2(a, b)',
       '#define BLOB_PAD(n) uint8_t BLOB_PAD_CAT(pad_, __LINE__)[n];', '']
conv = ['/* Generated by tools/gen_blobs.py: do not edit.  The members of each level\'s blob that are converted on load: offset in the blob, elements, size, kind (0 integer, 1 pointer). */']
def decl(t, n, cnt):
    arr = f'[{cnt}]' if cnt > 1 else ''
    if t == 'code':
        return f'void (*{n}{arr})(void);'
    if t in records:
        return f'struct {t} {n}{arr};'
    return f'{CT[t]}{"" if t == "ptr" else " "}{n}{arr};'

def pad_to(lines, pos, a, indent='    '):
    if a > pos:
        lines.append(f'{indent}BLOB_PAD({a - pos})')

records = {}
files = sorted((root / 'blobs').glob('*.blob'))
for f in files:
    cur = None
    for l in f.read_text().split('\n'):
        t = l.split(';')[0].split()
        if not t:
            continue
        if t[0] == 'record':
            cur = records[t[1]] = {'size': int(t[2]), 'fields': []}
        elif t[0] == 'end':
            cur = None
        elif t[0] == 'raw':
            pass
        elif cur is not None:
            cur['fields'].append((int(t[0]), t[1], t[2], int(t[3]) if len(t) > 3 else 1))
for rn, r in records.items():
    out.append(f'struct {rn} {{')
    pos = 0
    for off, n, t, c in sorted(r['fields']):
        pad_to(out, pos, off)
        out.append('    ' + decl(t, n, c))
        pos = off + (records[t]['size'] if t in records else SIZE[t]) * c
    pad_to(out, pos, r['size'])
    out.append('};')
    out.append(f'_Static_assert(sizeof(struct {rn}) == {r["size"]}, "{rn}");')
    out.append('')

def conv_entries(base, t, cnt):
    """the converted members of CNT elements of type T at offset BASE in the blob"""
    if t in records:
        r = records[t]
        res = []
        for k in range(cnt):
            for off, n, ft, c in sorted(r['fields']):
                res += conv_entries(base + k * r['size'] + off, ft, c)
        return res
    return [(base, cnt, SIZE[t], KIND[t])] if t != 'u8' else []

for f in files:
    m = re.search(r'level(\d)', f.name)
    if not m:
        continue
    lv = m.group(1)
    rows = []
    cur = None
    raw = False
    for l in f.read_text().split('\n'):
        t = l.split(';')[0].split()
        if not t:
            continue
        if t[0] == 'raw':
            raw = True
        elif t[0] == 'record':
            cur = True
        elif t[0] == 'end':
            cur = None
        elif cur is None:
            rows.append((int(t[0], 16), t[1], t[2], int(t[3]) if len(t) > 3 else None))
    rows.sort()
    name = f'Level{lv}Blob'
    out.append(f'struct {name} {{')
    pos = BASE
    checks, members = [], []
    for i, (a, n, t, cnt) in enumerate(rows):
        esize = records[t]['size'] if t in records else SIZE[t]
        if a > pos:
            out.append(f'    BLOB_PAD({a - pos})')
            pos = a
        nxt = rows[i + 1][0] if i + 1 < len(rows) else a + esize
        if cnt is None:
            cnt = max(1, nxt - a) if t == 'u8' else 1
        size = cnt * esize
        if a + size > nxt and i + 1 < len(rows):
            sys.exit(f'{f.name}: {n} at {a:05X} runs into {rows[i + 1][1]}')
        if esize % 2 == 0 and a % 2:
            sys.exit(f'{f.name}: {n} at {a:05X} is not even')
        arr = f'[{cnt}]' if cnt > 1 else ''
        if t in records:
            out.append(f'    struct {t} {n}{arr};   /* {a:05X} */')
        else:
            out.append(f'    {decl(t, n, cnt)}   /* {a:05X} */')
        members += [] if raw else conv_entries(a - BASE, t, cnt)
        pos = a + size
        checks.append((n, a))
    out.append('};')
    for n, a in checks:
        out.append(f'_Static_assert(offsetof(struct {name}, {n}) == 0x{a:05X} - BLOB_BASE, "{name}.{n}");')
    out.append(f'#define level{lv}_blob (*(struct {name} *)GPTR(BLOB_BASE))')
    out.append('')
    conv.append(f'static const struct blob_member blob_members_{lv}[] = {{')
    conv += [f'    {{ 0x{o:X}, {c}, {s_}, {k} }},' for o, c, s_, k in members]
    conv.append('};')
out.append('#endif')
(root / 'blobs.h').write_text('\n'.join(out) + '\n')
(root / 'guest_blob.h').write_text('\n'.join(conv) + '\n')
