#!/usr/bin/env python3
"""native/src/blobs/levelN.blob and shop.blob -> native/src/level.h, levelN.h, shop.h and native/src/guest_blob.h.
level.h: the records of level1.blob (the engine's: SpawnRec, SpawnDef, the formations ...), shared by the levels, and the BLOB_ macros.
levelN.h (N 2..5) and shop.h: between the markers, the records defined in levelN.blob / shop.blob and struct LevelNData / ShopData, the layout of the blob of level N at $54E40 (the `blob` lines of symbols/weapons.symbols put them in a union in struct Xenon2: level1_data ... level5_data); level1.h has struct Level1Data.  A header that does not exist is made, one that does keeps what is outside the markers.
guest_blob.h: the members the host build converts (big endian -> its byte order, addresses -> pointers) when the blob is loaded.

A line is `ADDR name TYPE [COUNT]` (hex address): u8 u16 s16 u32 (integers), cell (a cell of the tile map, COUNT cells), ptr (a pointer to the blob, const uint8_t *), code (a pointer to
a function of the original's code: the C function), or the name of a record.  `record NAME SIZE` starts a record: lines `OFFSET name TYPE [COUNT]`
(decimal offset), `end` closes it.  u16 u32 and ptr members are native
(converted on load: read and write them directly); u8 members are bytes (text, rates, flags, sample data) and are not converted.  Words are u16 (cells, pictures, animation scripts); `ptr:u16` is a pointer to words.
COUNT defaults to 1; a u8 member without it runs to the next one.  What no member covers is padding (the level's code)."""
import re, sys, pathlib

BASE = 0x54E40
END = 0x7d120   # (the first byte of level_data_dst: the loaded level files end below it)
SIZE = {'u8': 1, 'cell': 2, 'u16': 2, 's16': 2, 'u32': 4, 'ptr': 4, 'code': 4}
KIND = {'u8': 0, 'cell': 0, 'u16': 0, 's16': 0, 'u32': 0, 'ptr': 1, 'code': 2}
CT = {'u8': 'uint8_t', 'cell': 'Cell', 'u16': 'uint16_t', 's16': 'int16_t', 'u32': 'uint32_t', 'ptr': 'const uint8_t *', 'code': 'void (*'}
root = pathlib.Path(__file__).resolve().parent.parent / 'native' / 'src'
head = ['#define BLOB_BASE 0x54E40', '',
        '#define BLOB_PAD(at, n) uint8_t pad_##at[n];   /* a gap between members, named by its offset */', '']
conv = ['/* Generated by tools/gen_blobs.py: do not edit.  The members of each level\'s blob that are converted on load: offset in the blob, elements, size, kind (0 integer, 1 pointer). */']
def decl(t, n, cnt):
    arr = f'[{cnt}]' if cnt > 1 else ''
    if t == 'ptr:u16':
        return f'const uint16_t *{n}{arr};'
    if t.startswith('ptr:'):
        return f'struct {t[4:]} *{n}{arr};'
    if t == 'code':
        return f'void (*{n}{arr})(void);'
    if t in records:
        return f'struct {t} {n}{arr};'
    return f'{CT[t]}{"" if t == "ptr" else " "}{n}{arr};'

def pad_to(lines, pos, a, indent='    '):
    if a > pos:
        lines.append(f'{indent}BLOB_PAD({pos:x}, {a - pos})')

records = {}
owner = {}   # record name -> the blob file that defines it
files = sorted((root / 'blobs').glob('*.blob'))
for f in files:
    cur = None
    for l in f.read_text().split('\n'):
        t = l.split(';')[0].split()
        if not t:
            continue
        if t[0] == 'record':
            cur = records[t[1]] = {'size': int(t[2]), 'fields': []}
            owner[t[1]] = f.name
        elif t[0] == 'end':
            cur = None
        elif t[0] == 'raw':
            pass
        elif cur is not None:
            cur['fields'].append((int(t[0]), t[1], t[2], int(t[3]) if len(t) > 3 else 1))
def header_of(blob_name):
    """the header that holds what level1.blob (shared), levelN.blob or shop.blob define"""
    m = re.match(r'level(\d)\.blob|(shop)\.blob', blob_name)
    return 'level' if blob_name == 'level1.blob' else (f'level{m.group(1)}' if m.group(1) else 'shop')

parts = {}   # header -> lines
def part(h):
    return parts.setdefault(h, [])

for rn, r in records.items():
    o = part(header_of(owner[rn]))
    o.append(f'struct {rn} {{')
    pos = 0
    for off, n, t, c in sorted(r['fields']):
        pad_to(o, pos, off)
        o.append('    ' + decl(t, n, c))
        pos = off + (records[t]['size'] if t in records else SIZE[t.split(':')[0]]) * c
    pad_to(o, pos, r['size'])
    o.append('};')
    o.append(f'_Static_assert(sizeof(struct {rn}) == {r["size"]}, "{rn}");')
    o.append('')

def conv_entries(base, t, cnt):
    """the converted members of CNT elements of type T at offset BASE in the blob"""
    if t in records:
        r = records[t]
        res = []
        for k in range(cnt):
            for off, n, ft, c in sorted(r['fields']):
                res += conv_entries(base + k * r['size'] + off, ft, c)
        return res
    return [(base, cnt, SIZE[t.split(':')[0]], KIND[t.split(':')[0]])] if t not in ('u8', 'cell') else []

def script_pointers(base, t, cnt, name):
    """the pointers to animation scripts in CNT elements of type T at offset BASE (a pointer to words whose name has anim)"""
    if t in records:
        res = []
        for k in range(cnt):
            for off, n, ft, c in sorted(records[t]['fields']):
                res += script_pointers(base + k * records[t]['size'] + off, ft, c, n)
        return res
    return [(base, cnt)] if t == 'ptr:u16' and 'anim' in name else []

for f in files:
    m = re.search(r'level(\d)|(shop)', f.name)
    if not m:
        continue
    lv = m.group(1) or m.group(2)
    rows = []
    cur = None
    raw = False
    for l in f.read_text().split('\n'):
        t = l.split(';')[0].split()
        if not t:
            continue
        if t[0] == 'raw':
            raw = True
        elif t[0] == 'record':
            cur = True
        elif t[0] == 'end':
            cur = None
        elif cur is None:
            rows.append((int(t[0], 16), t[1], t[2], int(t[3]) if len(t) > 3 else None))
    rows.sort()
    name = f'Level{lv}Data' if lv.isdigit() else f'{lv.capitalize()}Data'
    out = part(f'level{lv}' if lv.isdigit() else 'shop')
    out.append(f'struct {name} {{')
    pos = BASE
    checks, members, script_ptrs, pads = [], [], [], []
    for i, (a, n, t, cnt) in enumerate(rows):
        esize = records[t]['size'] if t in records else SIZE[t.split(':')[0]]
        if a > pos:
            out.append(f'    BLOB_PAD({pos - BASE:x}, {a - pos})')
            pads.append((pos - BASE, a - pos))
            pos = a
        nxt = rows[i + 1][0] if i + 1 < len(rows) else a + esize
        if cnt is None:
            cnt = max(1, nxt - a) if t == 'u8' else 1
        size = cnt * esize
        if a + size > nxt and i + 1 < len(rows):
            sys.exit(f'{f.name}: {n} at {a:05X} runs into {rows[i + 1][1]}')
        if esize % 2 == 0 and a % 2:
            sys.exit(f'{f.name}: {n} at {a:05X} is not even')
        arr = f'[{cnt}]' if cnt > 1 else ''
        if t in records:
            out.append(f'    struct {t} {n}{arr};   /* {a:05X} */')
        else:
            out.append(f'    {decl(t, n, cnt)}   /* {a:05X} */')
        members += [] if raw else conv_entries(a - BASE, t, cnt)
        script_ptrs += [] if raw else script_pointers(a - BASE, t, cnt, n)
        pos = a + size
        checks.append((n, a))
    out.append('};')
    if pos > END:
        sys.exit(f'{f.name}: runs past ${END:X}')
    out.append(f'_Static_assert(sizeof(struct {name}) == {pos - BASE}, "{name}");')
    for n, a in checks:
        out.append(f'_Static_assert(offsetof(struct {name}, {n}) == 0x{a:05X} - BLOB_BASE, "{name}.{n}");')
    out.append('')
    conv.append(f'static const struct blob_member blob_members_{lv}[] = {{')
    conv += [f'    {{ 0x{o:X}, {c}, {s_}, {k} }},' for o, c, s_, k in members]
    conv.append('};')
    conv.append(f'static const struct {{ uint32_t offset, size; }} blob_pads_{lv}[] = {{   /* the bytes no member names (tools/blob_gaps.py reads them) */')
    conv += [f'    {{ 0x{o:X}, {z} }},' for o, z in pads]
    conv.append('};')
    conv.append(f'static const struct {{ uint32_t offset, count; }} blob_script_pointers_{lv}[] = {{   /* the pointers to scripts */')
    conv += [f'    {{ 0x{o:X}, {c} }},' for o, c in script_ptrs]
    conv.append('};')
    conv.append(f'static const struct {{ uint32_t offset, size; }} blob_scripts_{lv}[] = {{   /* the animation scripts: where the walk of the loader starts */')
    conv += [f'    {{ 0x{x - BASE:X}, {c * 2} }},' for x, c in sorted((a, cnt or 1) for a, n, t, cnt in rows if t == 'u16' and 'anim' in n)]
    conv.append('};')
BEGIN = '/* BEGIN generated by tools/gen_blobs.py from blobs/%s.blob: do not edit up to the END marker */'
END = '/* END generated */'

def write_region(h, blob):
    """the generated types of one level or of the shop go between the markers of its header, before its own includes"""
    path = root / f'{h}.h'
    uses = [] if h == 'level' else ['#include "level.h"']   # (the records and macros the blobs share)
    region = '\n'.join([BEGIN % blob, '#include <stdint.h>', '#include <stddef.h>', '#include "types.h"'] + uses + [''] + (head if h == 'level' else []) + part(h) + [END])
    guard = h.upper() + '_H'
    if path.exists():
        text = path.read_text()
        a = text.find('/* BEGIN generated')
        b = text.find(END)
        if a < 0 or b < 0:
            sys.exit(f'{path.name}: no generated markers')
        text = text[:a] + region + text[b + len(END):]
    else:
        text = f'#ifndef {guard}\n#define {guard}\n{region}\n' + ('' if h == 'level' else '#include "game.h"\n') + '#endif\n'
    path.write_text(text)

for h in sorted(parts):
    write_region(h, 'level1' if h == 'level' else h)
(root / 'guest_blob.h').write_text('\n'.join(conv) + '\n')
