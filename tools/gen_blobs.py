#!/usr/bin/env python3
"""native/src/blobs/levelN.blob -> native/src/blobs.h: struct LevelNBlob, the layout of the code blob of level N at $54E00.
A line is `ADDR name u8|u16|u32` (hex address).  A member runs to the next one (count = gap / size, the rest is padding); the last has one element.
A member at an odd address, or with less room than its size, is bytes.
The fields are raw big-endian memory: read them with rd16/rd32 (the host build is little-endian), or through the *_AT macros."""
import re, sys, pathlib

BASE = 0x54E00
SIZE = {'u8': 1, 'u16': 2, 'u32': 4}
CT = {'u8': 'uint8_t', 'u16': 'uint16_t', 'u32': 'uint32_t'}
root = pathlib.Path(__file__).resolve().parent.parent / 'native' / 'src'
out = ['/* Generated by tools/gen_blobs.py from blobs/*.blob: do not edit.  The code blob of each level at $54E00 as raw big-endian memory. */',
       '#ifndef BLOBS_H', '#define BLOBS_H', '#include <stdint.h>', '#include <stddef.h>', '',
       '#define BLOB_BASE 0x54E00', '#define BLOB_ADDR(S, f) (BLOB_BASE + offsetof(struct S, f))', '',
       '#define BLOB_PAD_CAT2(a, b) a##b', '#define BLOB_PAD_CAT(a, b) BLOB_PAD_CAT2(a, b)',
       '#define BLOB_PAD(n) uint8_t BLOB_PAD_CAT(pad_, __LINE__)[n];', '']
for f in sorted((root / 'blobs').glob('level*.blob')):
    lv = re.search(r'level(\d)', f.name).group(1)
    rows = []
    for l in f.read_text().split('\n'):
        l = l.split(';')[0].split()
        if l:
            rows.append((int(l[0], 16), l[1], l[2]))
    rows.sort()
    name = f'Level{lv}Blob'
    out.append(f'struct {name} {{')
    pos = BASE
    checks = []
    for i, (a, n, t) in enumerate(rows):
        if a > pos:
            out.append(f'    BLOB_PAD({a - pos})')
            pos = a
        end = rows[i + 1][0] if i + 1 < len(rows) else a + SIZE[t]
        gap = end - a
        if SIZE[t] > gap or (a % 2 and SIZE[t] > 1):   # overlaps the next member, or odd: kept as bytes
            overlap = SIZE[t] > gap
            t, cnt, rest = 'u8', gap, 0
            out.append(f'    {CT[t]} {n}' + (f'[{cnt}]' if cnt > 1 else '') + f';   /* {a:05X}' + (': a word read here overlaps the next member */' if overlap else ': odd address, read with rd16/rd32 */'))
            pos = end
            checks.append((n, a))
            continue
        cnt = gap // SIZE[t]
        rest = end - a - cnt * SIZE[t]
        out.append(f'    {CT[t]} {n}' + (f'[{cnt}]' if cnt > 1 else '') + f';   /* {a:05X} */')
        if rest:
            out.append(f'    BLOB_PAD({rest})')
        pos = end
        checks.append((n, a))
    out.append('};')
    for n, a in checks:
        out.append(f'_Static_assert(offsetof(struct {name}, {n}) == 0x{a:05X} - BLOB_BASE, "{name}.{n}");')
    out.append('')
out.append('#endif')
(root / 'blobs.h').write_text('\n'.join(out) + '\n')
